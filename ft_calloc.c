#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void	*memory_ptr;

	if (nmemb != 0 && size > ((size_t)-1) / nmemb)
		return (NULL);
	memory_ptr = malloc(nmemb * size);
	if (!memory_ptr)
		return (NULL);
	ft_bzero(memory_ptr, nmemb * size);
	return (memory_ptr);
}
